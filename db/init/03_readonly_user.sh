#!/bin/bash
# 建立只授 SELECT 權限的唯讀帳號，供 flask-api 連線使用。
# 帳號密碼由 .env 傳入（MYSQL_READONLY_USER / MYSQL_READONLY_PASSWORD），不寫死在檔案中。
set -euo pipefail

: "${MYSQL_READONLY_USER:?MYSQL_READONLY_USER 未設定}"
: "${MYSQL_READONLY_PASSWORD:?MYSQL_READONLY_PASSWORD 未設定}"

mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<SQL
CREATE USER IF NOT EXISTS '${MYSQL_READONLY_USER}'@'%' IDENTIFIED BY '${MYSQL_READONLY_PASSWORD}';
GRANT SELECT ON meddb.* TO '${MYSQL_READONLY_USER}'@'%';
FLUSH PRIVILEGES;
SQL

echo "唯讀帳號 ${MYSQL_READONLY_USER} 建立完成（僅 SELECT on meddb.*）"
